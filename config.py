"""Единое место для настроек оборудования и логики сканирования.

Этот файл не выполняет действий сам: остальные модули импортируют из него
константы. Поэтому перед работой с реальным оборудованием менять параметры
нужно здесь, а не в коде интерфейса или сканера.
"""

# --- Последовательное подключение 3D-принтера -----------------------------
# Путь Linux к USB-порту платы принтера. Проверить его можно командой
# `ls /dev/ttyUSB* /dev/ttyACM*` при подключённом принтере.
PRINTER_PORT = "/dev/ttyUSB0"
# Скорость serial-обмена. Должна совпадать с настройкой прошивки принтера.
PRINTER_BAUDRATE = 115200

# --- Геометрия стола --------------------------------------------------------
# Физические пределы координат сопла в миллиметрах. Они используются, чтобы
# приложение не отправило принтер за границы стола.
BED_SIZE_X = 220.0
BED_SIZE_Y = 220.0
BED_MAX_Z = 250.0
# Центр стола — начало системы координат измерений. Магнит кладётся сюда,
# поэтому координата датчика (0, 0) означает центр магнита и центр стола.
BED_CENTER_X = BED_SIZE_X / 2.0
BED_CENTER_Y = BED_SIZE_Y / 2.0

# --- Смещение датчика относительно сопла -----------------------------------
# Датчик закреплён не на самом сопле. Формула связи такая:
# sensor_x = printer_x + SENSOR_OFFSET_X
# sensor_y = printer_y + SENSOR_OFFSET_Y
# Сканер вычитает эти значения, чтобы в нужную точку приехал именно датчик.
SENSOR_OFFSET_X = 18.0
SENSOR_OFFSET_Y = -26.0

# --- Высота измерения -------------------------------------------------------
# Расстояние между датчиком и верхней поверхностью магнита. Рабочая координата
# Z вычисляется как высота магнита + SCAN_HEIGHT.
SCAN_HEIGHT = 5.0

# --- Скорости G-code --------------------------------------------------------
# Все значения передаются прошивке как F в миллиметрах в минуту.
# MOVE_SPEED — быстрый переход к первой точке;
# SCAN_SPEED — перемещения между измерениями;
# Z_SPEED — только подъёмы и опускания по оси Z.
MOVE_SPEED = 8000
SCAN_SPEED = 6000
Z_SPEED = 1500
# Скорости и задержки для мгновенного автопоиска центра магнита:
SEARCH_SPEED = 9000
SEARCH_Z_SPEED = 2500
SEARCH_SETTLE_TIME = 0.002
SEARCH_SAFE_Z = 25.0
# После остановки в каждой точке механизм успокаивается перед измерением.
# 0.10 с (100 мс) достаточно для полного гашения вибраций лёгкого датчика
# после M400, что сокращает задержку на каждой точке почти в 3 раза.
POINT_SETTLE_TIME = 0.10

# --- MLX90393 и шина I²C ----------------------------------------------------
# Номер Linux-шины `/dev/i2c-1` и 7-битный I²C-адрес MLX90393.
I2C_BUS = 1
MLX90393_ADDRESS = 0x0C

# Настройки коэффициента усиления (Gain) и разрешения (Resolution) датчика.
# В чипе MLX90393 усиление определяет физический диапазон измерения:
# - GAIN_SEL=0 (adafruit_mlx90393.GAIN_5X = 0) даёт минимальное усиление и максимальный
#   диапазон до ~42-50 мТл без насыщения на постоянных магнитах.
# - GAIN_SEL=7 (adafruit_mlx90393.GAIN_1X = 7) даёт максимальное усиление, но насыщается уже
#   при ~7.9 мТл (что приводило к ограничению измерений 7 мТл на мощных магнитах).
# По умолчанию используем 0 (GAIN_5X) для устранения эффекта насыщения при сканировании.
SENSOR_GAIN = 0
SENSOR_RESOLUTION = 0  # 0 = RESOLUTION_16 (16-битный со знаком)
SENSOR_AUTO_GAIN = True  # Автоматическое понижение усиления при обнаружении насыщения

# --- Файлы результатов ------------------------------------------------------
# Относительная папка, в которую csv_export.py создаёт CSV после сканирования.
RESULTS_FOLDER = "results"

# --- Обработка показаний ----------------------------------------------------
# Количество чтений датчика на точку. MLX90393 уже имеет аппаратную фильтрацию
# FILTER_7 и усреднение OSR_3 (шум < 0.00035 мТл). 1 чтение экономит 444 мс на точке.
SAMPLES_PER_POINT = 1
# Если во время сканирования MLX90393 кратковременно пропал (помеха на шине,
# дребезг контакта, просадка питания), чтение ждёт ответ до этого числа секунд
# и продолжает измерение, как только датчик снова ответит. По истечении срока
# скан останавливается с ошибкой, чтобы не мерить вслепую.
SENSOR_RECONNECT_TIMEOUT = 5.0

# --- Тестовая функция «автопоиск центра магнита» -----------------------------
# Принтер ищет магнит по максимуму модуля |B| на рабочей высоте измерения.
# Поле диполя убывает с расстоянием, поэтому прямо над центром полюса |B|
# максимален. Грубый проход идёт кольцами от центра стола наружу; по умолчанию
# проверяется вся сетка, потому что реальное поле может иметь несколько
# полюсов, шум и внешнее поле. Затем
# уточняющая сетка вокруг найденного пика превращает его в точный центр через
# взвешенный «центр масс» поля. После этого выполняются контрольные измерения
# по окружности найденного центра. Все размеры — в миллиметрах в системе
# координат измерений (0, 0 — центр стола).
SEARCH_HALF_RANGE = 30.0      # Радиус максимального кольца грубого поиска.
SEARCH_COARSE_STEP = 10.0     # Шаг колец грубого поиска (первый проход).
SEARCH_FINE_HALF = 8.0        # Половина стороны окна уточнения вокруг грубого пика.
SEARCH_FINE_STEP = 3.0        # Шаг уточняющей сетки (второй проход).
SEARCH_TEST_RADIUS = 10.0     # Радиус контрольной окружности после поиска центра.
SEARCH_TEST_POINTS = 12       # Число точек контрольной окружности.
# Ранний выход предполагает, что поле единственного магнита монотонно
# убывает от центра. Для реального сканера это нельзя считать гарантией:
# шум, несколько полюсов и внешнее поле могут дать ложный пик.
SEARCH_EARLY_STOP = False

# --- Метаданные приложения --------------------------------------------------
PROJECT_NAME = "Magnetic Map"
