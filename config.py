"""Единое место для настроек оборудования и логики сканирования.

Этот файл не выполняет действий сам: остальные модули импортируют из него
константы. Поэтому перед работой с реальным оборудованием менять параметры
нужно здесь, а не в коде интерфейса или сканера.
"""

# --- Последовательное подключение 3D-принтера -----------------------------
# Путь Linux к USB-порту платы принтера. Проверить его можно командой
# `ls /dev/ttyUSB* /dev/ttyACM*` при подключённом принтере.
PRINTER_PORT = "/dev/ttyUSB0"
# Скорость serial-обмена. Должна совпадать с настройкой прошивки принтера.
PRINTER_BAUDRATE = 115200

# --- Геометрия стола --------------------------------------------------------
# Физические пределы координат сопла в миллиметрах. Они используются, чтобы
# приложение не отправило принтер за границы стола.
BED_SIZE_X = 220.0
BED_SIZE_Y = 220.0
# Центр стола — начало системы координат измерений. Магнит кладётся сюда,
# поэтому координата датчика (0, 0) означает центр магнита и центр стола.
BED_CENTER_X = BED_SIZE_X / 2.0
BED_CENTER_Y = BED_SIZE_Y / 2.0

# --- Смещение датчика относительно сопла -----------------------------------
# Датчик закреплён не на самом сопле. Формула связи такая:
# sensor_x = printer_x + SENSOR_OFFSET_X
# sensor_y = printer_y + SENSOR_OFFSET_Y
# Сканер вычитает эти значения, чтобы в нужную точку приехал именно датчик.
SENSOR_OFFSET_X = 14.0
SENSOR_OFFSET_Y = -20.0

# --- Высота измерения -------------------------------------------------------
# Расстояние между датчиком и верхней поверхностью магнита. Рабочая координата
# Z вычисляется как высота магнита + SCAN_HEIGHT.
SCAN_HEIGHT = 5.0

# --- Скорости G-code --------------------------------------------------------
# Все значения передаются прошивке как F в миллиметрах в минуту.
# MOVE_SPEED — быстрый переход к первой точке;
# SCAN_SPEED — перемещения между измерениями;
# Z_SPEED — только подъёмы и опускания по оси Z.
MOVE_SPEED = 7000
SCAN_SPEED = 5000
Z_SPEED = 1500
# После остановки в каждой точке механизм немного успокаивается, чтобы вибрация
# не влияла на показание магнитного датчика. Значение задаётся в секундах.
# Для текущей механики и MLX90393 пауза увеличена: датчику нужно больше
# времени, чтобы показание стабилизировалось после движения.
POINT_SETTLE_TIME = 0.30

# --- MLX90393 и шина I²C ----------------------------------------------------
# Номер Linux-шины `/dev/i2c-1` и 7-битный I²C-адрес MLX90393.
I2C_BUS = 1
MLX90393_ADDRESS = 0x0C

# --- Файлы результатов ------------------------------------------------------
# Относительная папка, в которую csv_export.py создаёт CSV после сканирования.
RESULTS_FOLDER = "results"

# --- Обработка показаний ----------------------------------------------------
# Количество быстрых чтений датчика для одной точки. Их среднее уменьшает шум.
SAMPLES_PER_POINT = 3

# --- Метаданные приложения --------------------------------------------------
PROJECT_NAME = "Magnetic Map"
PROJECT_VERSION = "2.0"
